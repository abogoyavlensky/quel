#!/usr/bin/env bash
# Print the Homebrew cask for a Quel release, from the release's
# checksums.txt. Release CI writes it to Casks/quel.rb in
# https://github.com/abogoyavlensky/homebrew-tap.
#
#   bash scripts/generate-cask.sh VERSION CHECKSUMS_FILE > quel.rb
#
# VERSION is MAJOR.MINOR.PATCH without the v prefix.
set -euo pipefail

source "$(dirname "$0")/macos-common.sh"

[[ $# -eq 2 ]] || die "usage: generate-cask.sh VERSION CHECKSUMS_FILE"
version="$1"
checksums="$2"

valid_version "$version" || die "VERSION must be MAJOR.MINOR.PATCH, got '$version'"
[[ -f "$checksums" ]] || die "checksums file not found: $checksums"

archive="$(archive_name "$version")"
matches="$(awk -v f="$archive" '$2 == f' "$checksums")"
[[ -n "$matches" ]] || die "no checksum for $archive in $checksums"
[[ "$(printf '%s\n' "$matches" | wc -l)" -eq 1 ]] || die "more than one checksum for $archive in $checksums"
read -r sha rest <<<"$matches"
[[ "$sha" =~ ^[0-9a-f]{64}$ && "$rest" == "$archive" ]] ||
    die "malformed checksum line for $archive in $checksums"

# Homebrew names macOS releases; MACOS_MIN is the one source for the minimum.
case "$MACOS_MIN" in
15.0) macos=sequoia ;;
26.0) macos=tahoe ;;
*) die "no Homebrew name for macOS $MACOS_MIN" ;;
esac

cat <<EOF
# Generated by scripts/generate-cask.sh in
# https://github.com/abogoyavlensky/quel. Do not edit.
cask "quel" do
  version "$version"
  sha256 "$sha"

  url "https://github.com/abogoyavlensky/quel/releases/download/v#{version}/quel_#{version}_darwin_arm64.zip"
  name "$APP_NAME"
  desc "Desktop database client"
  homepage "https://github.com/abogoyavlensky/quel"

  livecheck do
    skip "Updated by Quel's release workflow"
  end

  depends_on arch: :arm64
  depends_on macos: ">= :$macos"

  app "$APP_NAME.app"
end
EOF
